#!/usr/bin/env bash
# Fast local preflight shared by developers and GitHub Actions.
# This checks contracts, Python/Node tests and launcher syntax. It does NOT
# compile or start lsFusion/MyCompany; native runtime smoke remains a separate gate.
set -Eeuo pipefail

SCRIPT_DIR="$(cd -- "$(dirname -- "${BASH_SOURCE[0]}")" && pwd)"
REPO_ROOT="$(cd -- "$SCRIPT_DIR/../.." && pwd)"
cd "$REPO_ROOT"

MODE="all"
case "${1:-}" in
  "") ;;
  --all) MODE="all" ;;
  --platform) MODE="platform" ;;
  --replenishment) MODE="replenishment" ;;
  --help|-h)
    cat <<'HELP'
Uso: bash scripts/platform/local-preflight.sh [--all|--platform|--replenishment]

  --all             Ejecuta las dos capas rápidas (opción predeterminada).
  --platform        Extensiones, configuración, supervisor y scripts de plataforma.
  --replenishment   Pruebas Python, fixtures y conversión del contrato de reposición.

No inicia PostgreSQL, lsFusion, Tomcat, Docker ni servicios externos.
No sustituye la compilación Maven ni la prueba autenticada del runtime nativo.
HELP
    exit 0
    ;;
  *)
    echo "Argumento no reconocido: $1" >&2
    exit 2
    ;;
esac

PYTHON_BIN="${PYTHON_BIN:-python3}"
NODE_BIN="${NODE_BIN:-node}"
command -v bash >/dev/null 2>&1 || { echo "No se encontró bash." >&2; exit 127; }
command -v "$PYTHON_BIN" >/dev/null 2>&1 || { echo "No se encontró Python: $PYTHON_BIN" >&2; exit 127; }
if [[ "$MODE" != "replenishment" ]]; then
  command -v "$NODE_BIN" >/dev/null 2>&1 || { echo "No se encontró Node.js: $NODE_BIN" >&2; exit 127; }
fi

OWN_OUTPUT_DIR=0
if [[ -n "${RUBROVA_PREFLIGHT_OUTPUT_DIR:-}" ]]; then
  OUTPUT_DIR="$RUBROVA_PREFLIGHT_OUTPUT_DIR"
  mkdir -p "$OUTPUT_DIR"
else
  OUTPUT_DIR="$(mktemp -d "${TMPDIR:-/tmp}/rubrova-preflight.XXXXXX")"
  OWN_OUTPUT_DIR=1
fi
cleanup() {
  if [[ "$OWN_OUTPUT_DIR" -eq 1 ]]; then
    rm -rf "$OUTPUT_DIR"
  fi
}
trap cleanup EXIT

export PYTHONUNBUFFERED=1
# Keep generated bytecode out of the working tree, including py_compile output.
export PYTHONPYCACHEPREFIX="$OUTPUT_DIR/pycache"

run_step() {
  printf '\n==> '
  printf '%q ' "$@"
  printf '\n'
  "$@"
}

echo "Rubrova preflight | modo=$MODE | repo=$REPO_ROOT"
echo "Salida temporal: $OUTPUT_DIR"

run_platform() {
  echo
  echo "===== CAPA PLATFORM ====="
  run_step "$PYTHON_BIN" -m py_compile \
    scripts/platform/apply-rubrova-source-patches.py \
    scripts/platform/test_apply_rubrova_source_patches.py
  run_step "$PYTHON_BIN" scripts/platform/test_apply_rubrova_source_patches.py
  run_step "$NODE_BIN" --test scripts/platform/validate-mycompany-extension.test.mjs
  run_step "$NODE_BIN" --test scripts/platform/audit-lsf-source.test.mjs
  run_step "$NODE_BIN" scripts/platform/audit-lsf-source.mjs --json-output "$OUTPUT_DIR/lsfusion-source-catalog.json"
  run_step "$NODE_BIN" --test scripts/evaluation/fixture-validator.test.mjs
  run_step "$PYTHON_BIN" scripts/platform/test_runtime_config.py
  run_step "$PYTHON_BIN" -m py_compile \
    scripts/platform/runtime-config.py \
    scripts/platform/run-local-native-preview.py \
    scripts/platform/native_runtime_url.py \
    scripts/platform/test_native_runtime_url.py \
    scripts/platform/native-postgres-backup.py \
    scripts/platform/test_native_postgres_backup.py \
    scripts/platform/inspect-mycompany-ui.py
  run_step "$PYTHON_BIN" scripts/platform/test_native_runtime_url.py
  run_step "$PYTHON_BIN" scripts/platform/test_runtime_native_preview.py
  run_step "$PYTHON_BIN" scripts/platform/test_native_postgres_backup.py

  local shell_file
  for shell_file in \
    scripts/platform/prepare-mycompany-6.2.sh \
    scripts/platform/deploy-mycompany-6.2.sh \
    scripts/platform/test-deploy-mycompany-6.2.sh \
    scripts/platform/test-runtime-smoke.sh \
    scripts/platform/test-runtime-native-smoke.sh \
    scripts/platform/native-listener-check.sh \
    scripts/platform/test-native-listener-check.sh \
    scripts/platform/run-local-preview-macos.sh \
    scripts/platform/build-rubrova-runtime-images.sh \
    "Iniciar Rubrova.command" \
    "Iniciar Rubrova - Demo.command" \
    scripts/platform/local-preflight.sh; do
    run_step bash -n "$shell_file"
  done
  run_step bash scripts/platform/test-native-listener-check.sh
  run_step bash scripts/platform/test-deploy-mycompany-6.2.sh
}

run_replenishment() {
  echo
  echo "===== CAPA REPLENISHMENT ====="
  run_step "$PYTHON_BIN" -m py_compile \
    scripts/replenishment/plan_replenishment.py \
    scripts/replenishment/test_plan_replenishment.py \
    scripts/replenishment/import_mycompany_snapshot.py \
    scripts/replenishment/test_import_mycompany_snapshot.py \
    scripts/replenishment/adapt_mycompany_native_export.py \
    scripts/replenishment/test_adapt_mycompany_native_export.py
  run_step "$PYTHON_BIN" -m unittest discover -s scripts/replenishment -p 'test_*.py'
  run_step "$PYTHON_BIN" scripts/replenishment/plan_replenishment.py \
    --fixture docs/fixtures/replenishment-planning.json \
    --output "$OUTPUT_DIR/replenishment-planning.json"
  run_step "$PYTHON_BIN" scripts/replenishment/import_mycompany_snapshot.py \
    --snapshot docs/fixtures/mycompany-replenishment-snapshot.json \
    --output "$OUTPUT_DIR/mycompany-replenishment-report.json"
  run_step "$PYTHON_BIN" scripts/replenishment/adapt_mycompany_native_export.py \
    --source docs/fixtures/mycompany-native-replenishment-export.json \
    --policy docs/fixtures/replenishment-planning-policy.json \
    --output "$OUTPUT_DIR/mycompany-native-normalized.json"
  run_step "$PYTHON_BIN" scripts/replenishment/import_mycompany_snapshot.py \
    --snapshot "$OUTPUT_DIR/mycompany-native-normalized.json" \
    --output "$OUTPUT_DIR/mycompany-native-replenishment-report.json"
}

case "$MODE" in
  all)
    run_platform
    run_replenishment
    ;;
  platform) run_platform ;;
  replenishment) run_replenishment ;;
esac

echo
echo "RUBROVA_PREFLIGHT=passed"
echo "RUBROVA_PREFLIGHT_MODE=$MODE"
echo "RUBROVA_PREFLIGHT_OUTPUT_DIR=$OUTPUT_DIR"
